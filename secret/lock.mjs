// encrypts everything in private/ into data/private.enc.js.
// Usage:  node tools/lock.mjs          (asks for the passphrase)
// private/ is in .gitignore, so the readable files are not committed.
// only the encrypted file is published. Without the passphrase it can't be read.

import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { pbkdf2Sync, randomBytes, createCipheriv } from "node:crypto";
import { createInterface } from "node:readline";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = join(ROOT, "private");
const OUT = join(ROOT, "data", "private.enc.js");
const ITERATIONS = 600000;

function collect(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) return collect(p);
    if (!/\.(md|txt)$/i.test(name)) return [];
    return [{ name: relative(SRC, p), text: readFileSync(p, "utf8") }];
  });
}

const ask = (q) => new Promise((res) => {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  rl.question(q, (a) => { rl.close(); res(a); });
});

if (!existsSync(SRC)) { console.error("No private/ folder yet. Create it and add .md files."); process.exit(1); }
const files = collect(SRC);
if (!files.length) { console.error("No .md or .txt files in private/"); process.exit(1); }

const pass = process.env.PRIVATE_PASSPHRASE || await ask("Passphrase (use 4+ random words): ");
if (pass.length < 12) { console.error("Passphrase too short: use at least 12 characters."); process.exit(1); }

const salt = randomBytes(16), iv = randomBytes(12);
const key = pbkdf2Sync(pass, salt, ITERATIONS, 32, "sha256");
const cipher = createCipheriv("aes-256-gcm", key, iv);
const data = Buffer.concat([cipher.update(JSON.stringify(files), "utf8"), cipher.final(), cipher.getAuthTag()]);

const b64 = (b) => b.toString("base64");
mkdirSync(join(ROOT, "data"), { recursive: true });
writeFileSync(OUT, `/* Encrypted private notes (AES-256-GCM, PBKDF2-SHA256). Generated by tools/lock.mjs. */
window.PRIVATE = ${JSON.stringify({ iterations: ITERATIONS, salt: b64(salt), iv: b64(iv), data: b64(data) })};
`);
console.log(`Encrypted ${files.length} file(s) into data/private.enc.js`);